-- Valores monetários sempre em centavos (BIGINT). Datas de lançamento em DATE (fuso America/Sao_Paulo).

CREATE TABLE profiles (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                    VARCHAR(254) NOT NULL UNIQUE,
    password_hash            VARCHAR(100),
    name                     VARCHAR(100),
    objective                VARCHAR(20),
    onboarding_done          BOOLEAN      NOT NULL DEFAULT FALSE,
    contribution_enabled     BOOLEAN      NOT NULL DEFAULT FALSE,
    contribution_bps         INT          NOT NULL DEFAULT 1000,
    contribution_category_id BIGINT,
    terms_accepted_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE category_catalog (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(60) NOT NULL,
    icon       VARCHAR(40) NOT NULL,
    group_name VARCHAR(30) NOT NULL,
    sort_order INT         NOT NULL
);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    name       VARCHAR(60) NOT NULL,
    kind       VARCHAR(12) NOT NULL,
    group_name VARCHAR(30) NOT NULL,
    icon       VARCHAR(40) NOT NULL,
    color      VARCHAR(12) NOT NULL,
    sort_order INT         NOT NULL,
    hidden     BOOLEAN     NOT NULL DEFAULT FALSE,
    goal_cents BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_categories_user ON categories (user_id, kind);

CREATE TABLE recurrences (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    kind              VARCHAR(12)  NOT NULL,
    category_id       BIGINT       NOT NULL REFERENCES categories (id),
    description       VARCHAR(120),
    amount_cents      BIGINT       NOT NULL,
    day_of_month      INT          NOT NULL,
    payment_method    VARCHAR(20),
    start_date        DATE         NOT NULL,
    end_date          DATE,
    generated_through DATE,
    fixed_bill        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_recurrences_user ON recurrences (user_id);

CREATE TABLE income_sources (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    name          VARCHAR(60)  NOT NULL,
    amount_cents  BIGINT       NOT NULL,
    fixed         BOOLEAN      NOT NULL,
    category_id   BIGINT       REFERENCES categories (id),
    recurrence_id BIGINT       REFERENCES recurrences (id) ON DELETE SET NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE installment_plans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    category_id       BIGINT       NOT NULL REFERENCES categories (id),
    description       VARCHAR(120),
    total_cents       BIGINT       NOT NULL,
    installment_count INT          NOT NULL,
    first_date        DATE         NOT NULL,
    payment_method    VARCHAR(20),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE import_batches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    file_name   VARCHAR(200) NOT NULL,
    row_count   INT          NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    undone_at   TIMESTAMP WITH TIME ZONE
);

CREATE TABLE transactions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    kind                VARCHAR(12)  NOT NULL,
    tx_date             DATE         NOT NULL,
    description         VARCHAR(120),
    category_id         BIGINT       NOT NULL REFERENCES categories (id),
    amount_cents        BIGINT       NOT NULL,
    payment_method      VARCHAR(20),
    status              VARCHAR(10)  NOT NULL,
    installment_number  INT,
    installment_total   INT,
    recurrence_id       BIGINT       REFERENCES recurrences (id) ON DELETE SET NULL,
    installment_plan_id BIGINT       REFERENCES installment_plans (id) ON DELETE SET NULL,
    origin              VARCHAR(10)  NOT NULL,
    import_batch_id     BIGINT       REFERENCES import_batches (id) ON DELETE SET NULL,
    note                VARCHAR(500),
    deleted_at          TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_tx_amount CHECK (amount_cents > 0)
);
CREATE INDEX ix_tx_user_date ON transactions (user_id, tx_date);
CREATE INDEX ix_tx_plan ON transactions (installment_plan_id);
CREATE INDEX ix_tx_recurrence ON transactions (recurrence_id);
CREATE INDEX ix_tx_batch ON transactions (import_batch_id);

CREATE TABLE magic_link_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE
);
