-- E-mails de aviso já enviados: garante que o mesmo aviso não sai duas vezes.
CREATE TABLE notification_log (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    kind    VARCHAR(20) NOT NULL,
    ref     VARCHAR(80) NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_notification_log UNIQUE (user_id, kind, ref)
);

-- Links de ação enviados por e-mail ("Marcar como paga"). Guardamos só o hash do token.
CREATE TABLE action_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    transaction_id BIGINT      NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    token_hash     VARCHAR(64) NOT NULL UNIQUE,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at        TIMESTAMP WITH TIME ZONE
);
